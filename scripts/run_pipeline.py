"""Run the whole RetainIQ pipeline end to end.

    python scripts/run_pipeline.py

Outputs land in data/processed/, models/ and reports/.
"""
from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
warnings.filterwarnings("ignore")

import joblib  # noqa: E402
import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from retainiq import cleaning, config, excel_export, experiment, modeling, segmentation, sql_analysis  # noqa: E402


def to_md(table: pd.DataFrame) -> str:
    """Small markdown-table writer (avoids an extra 'tabulate' dependency)."""
    head = "| " + " | ".join(map(str, table.columns)) + " |"
    sep = "|" + "---|" * len(table.columns)
    body = ["| " + " | ".join(map(str, row)) + " |" for row in table.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def banner(text):
    print(f"\n{'=' * 70}\n{text}\n{'=' * 70}")


def main():
    for d in (config.PROCESSED_DIR, config.MODEL_DIR, config.REPORTS_DIR, config.FIGURES_DIR):
        d.mkdir(parents=True, exist_ok=True)
    pd.set_option("display.width", 160, "display.max_columns", 20)
    results = {}

    # 1. Cleaning --------------------------------------------------------------
    banner("STEP 1  Data cleaning")
    df, before, after = cleaning.run()
    qa = pd.DataFrame({"before": before, "after": after})
    print(qa.to_string())
    results["data_quality"] = {"before": before, "after": after}
    qa.to_csv(config.REPORTS_DIR / "data_quality_before_after.csv")

    # 2. SQL -------------------------------------------------------------------
    banner("STEP 2  SQL analysis (SQLite)")
    sql_analysis.load_to_sqlite(df)
    sql_out = sql_analysis.run_queries()
    md = ["# SQL results\n", "Generated by `scripts/run_pipeline.py` from `sql/churn_analysis.sql`.\n"]
    for name, table in sql_out.items():
        print(f"\n-- {name}\n{table.to_string(index=False)}")
        md += [f"\n## {name}\n", to_md(table), ""]
    (config.REPORTS_DIR / "sql_results.md").write_text("\n".join(md), encoding="utf-8")
    results["overall_churn_rate_pct"] = float(sql_out["q1_overall_churn"]["churn_rate_pct"][0])

    # 4. Models (run before segmentation: segments need the model's scores) ----
    banner("STEP 4  Model comparison")
    table, best, fitted, (X_train, X_test, y_train, y_test) = modeling.compare_models(df)
    print(table.round(4).to_string(index=False))
    print(f"\nBest model (highest 5-fold CV F2 on training data): {best}")
    table.round(4).to_csv(config.REPORTS_DIR / "model_comparison.csv", index=False)
    results["model_comparison"] = table.round(4).to_dict(orient="records")
    results["best_model"] = best
    results["split"] = {"train_rows": len(X_train), "test_rows": len(X_test)}

    imp, shap_values, Xe = modeling.shap_importance(fitted[best], X_train, X_test)
    print("\nTop 10 churn drivers (mean |SHAP|):")
    print(imp[["plain_english", "mean_abs_shap"]].round(4).to_string(index=False))
    imp.round(5).to_csv(config.REPORTS_DIR / "top10_churn_drivers.csv", index=False)
    results["top10_drivers"] = imp["plain_english"].tolist()

    import shap
    Xe_readable = Xe.copy()
    Xe_readable.columns = [modeling._readable(c)[0] for c in Xe.columns]
    plt.figure()
    shap.summary_plot(shap_values, Xe_readable, max_display=10, show=False)
    plt.title(f"Top 10 churn drivers: {best}")
    plt.tight_layout()
    plt.savefig(config.FIGURES_DIR / "shap_summary.png", dpi=130)
    plt.close("all")

    # 3. Segmentation ------------------------------------------------------------
    banner("STEP 3  Risk segmentation (out-of-fold churn scores)")
    df["churn_score"] = modeling.out_of_fold_scores(df, best)
    df["risk_group"] = segmentation.assign_risk_group(df["churn_score"]).values
    seg = segmentation.segment_summary(df)
    print(seg.round(2).to_string(index=False))
    seg.round(3).to_csv(config.REPORTS_DIR / "risk_segments.csv", index=False)
    results["segments"] = seg.round(3).to_dict(orient="records")
    df.to_csv(config.SCORED_CSV, index=False)

    final = modeling.fit_final(df, best)
    joblib.dump({"pipeline": final, "model_name": best, "features": modeling.FEATURES}, config.MODEL_PATH)

    # 5. Experiment --------------------------------------------------------------
    banner("STEP 5  Retention experiment (High-risk, test vs control)")
    res, outcomes = experiment.run_experiment(df)
    for k, v in res.to_dict().items():
        print(f"{k:35s} {v:,.4f}" if isinstance(v, float) else f"{k:35s} {v}")
    outcomes[[config.ID_COL, "group", "churned_after", "retained", "MonthlyCharges"]].to_csv(
        config.REPORTS_DIR / "experiment_assignments.csv", index=False)
    high_n = int((df["risk_group"] == "High").sum())
    sens = experiment.sensitivity(df)
    print("\nSensitivity to the assumed uplift:")
    print(sens.round(4).to_string(index=False))
    sens.round(4).to_csv(config.REPORTS_DIR / "experiment_sensitivity.csv", index=False)
    (config.REPORTS_DIR / "experiment_readout.md").write_text(
        experiment.readout_markdown(res, high_n, sens), encoding="utf-8")
    results["experiment"] = res.to_dict()
    results["experiment_sensitivity"] = sens.round(4).to_dict(orient="records")

    # 7. Excel -------------------------------------------------------------------
    banner("STEP 7  Excel MIS")
    excel_export.build_workbook(df, seg)
    pivot = excel_export.python_pivot(df)
    print("Churn % by Contract x Tenure (pandas check of the Excel pivot):")
    print(pivot.to_string())
    results["pivot_contract_x_tenure_pct"] = pivot.to_dict()
    print(f"Saved {config.EXCEL_PATH}")

    (config.REPORTS_DIR / "results.json").write_text(json.dumps(results, indent=2, default=float), encoding="utf-8")
    banner("DONE: see reports/ for every output")


if __name__ == "__main__":
    main()
